const Rectangle REGIONES[5]={
    {0,0,0,0}, // Si es cero no se hace nada
    {0,160,ANCHO_LOSA,ALTO_LOSA},
    {32,160,ANCHO_LOSA,ALTO_LOSA},
    {0,352,ANCHO_LOSA,ALTO_LOSA},
    {224,512,32,32}, // nido
};

bool posicion_libre(Vector2 destino) {
    // Traducir posición del personaje a losa, es decir, a celda de la matriz
    int col=(int)(floor(destino.x/ANCHO_LOSA));
    int fila=(int)(floor(destino.y/ALTO_LOSA));

    for (int i=fila; i<=fila+1; i++) {
        for (int j=col; j<=col+1; j++) {
            if (ESCENARIO[i][j] <= 2) return false;
        }
    }
    return true;
}

int dibuja_escenario() {
    int losas_dibujadas=0;

    int col_min=(ren.losa.x-rango_horizontal>0)? ren.losa.x-rango_horizontal : 0;
    int col_max=(ren.losa.x+rango_horizontal<ANCHO_ESCENARIO)? ren.losa.x+rango_horizontal : ANCHO_ESCENARIO;
    int fila_min=(ren.losa.y-rango_vertical>0)? ren.losa.y-rango_vertical : 0;
    int fila_max=(ren.losa.y+rango_vertical<ALTO_ESCENARIO)? ren.losa.y+rango_vertical : ALTO_ESCENARIO;
    for (int i=fila_min; i<fila_max; i++) {
        for (int j=col_min; j<col_max; j++) {
            if (ESCENARIO[i][j]<=0) continue;
            DrawTextureRec(tiles, REGIONES[ESCENARIO[i][j]], (Vector2){j*ANCHO_LOSA, i*ALTO_LOSA}, WHITE);
            losas_dibujadas++;
        }
    }

    return losas_dibujadas;
}
